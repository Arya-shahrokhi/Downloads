export async function seedArticles() {
  try {
    const count = await Article.countDocuments();
    if (count > 0) {
      console.log(`مقالات از قبل وجود دارند (${count}). دوباره seed نمی‌شوند.`);
      return;
    }
    await Article.insertMany(articles);
    console.log(`✓ ${articles.length} مقاله seed شد`);
  } catch (err) {
    console.error('خطا در seed مقالات:', err.message);
  }
}
