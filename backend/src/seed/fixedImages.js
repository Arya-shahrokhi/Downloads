/** نام‌ها را بدون نیم‌فاصله/فاصله و با ی/ک فارسی مقایسه می‌کنیم. */
export const normalizeName = (s = '') => String(s)
  .replace(/ي/g, 'ی')
  .replace(/ك/g, 'ک')
  .replace(/[\u200c\s]+/g, '')
  .trim();

const byName = new Map(Object.entries(fixedImageFiles).map(([name, file]) => [normalizeName(name), file]));

/** آدرس عکس جدید محصول (URL-encoded) یا null اگر عکسی در fixed/ ندارد. */
export const fixedImageUrl = (name) => {
  const file = byName.get(normalizeName(name));
  return file ? encodeURI(FIXED_DIR + file) : null;
};

/** اگر عکس جدید وجود داشته باشد، جایگزین تصاویر محصول می‌شود. */
export const withFixedImage = (product) => {
  const url = fixedImageUrl(product.name);
  return url ? { ...product, images: [{ url, alt: product.name }] } : product;
};
