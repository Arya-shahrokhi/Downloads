const normalizeName = (value) => String(value || '').replace(/\u200c/g, ' ').replace(/\s+/g, ' ').trim();

/** Finds the editorial content for a category by slug or Persian name. */
export function findCategoryContent({ slug, name } = {}) {
  if (slug) {
    const bySlug = CATEGORY_CONTENT.find((c) => c.slug === slug);
    if (bySlug) return bySlug;
  }
  if (name) {
    const n = normalizeName(name);
    return CATEGORY_CONTENT.find((c) => c.names.some((alias) => normalizeName(alias) === n)) || null;
  }
  return null;
}

/** Preferred clean slug for a Persian category name (used by seed + migration). */
export const categorySlugFor = (name) => findCategoryContent({ name })?.slug || null;
